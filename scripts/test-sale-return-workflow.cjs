const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium, expect } = require("@playwright/test");
const base = new URL(process.env.APP_URL || "http://127.0.0.1:5217/");
assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(base.hostname));
const output = path.resolve(process.env.QA_OUTPUT_DIR || "artifacts/qa/reliability-returns/returns-browser");
const results = [];
const corrections = process.env.RETURN_CORRECTIONS === "true";

async function main() {
  fs.mkdirSync(output, { recursive: true });
  const { createEmptyFlipScoutState } = await import("../src/features/flipScout/constants.js");
  const seed = createEmptyFlipScoutState();
  seed.inventory = [{ id: "return-stock", name: "Synthetic Aurora pair", quantity: 2, ownedItemPurpose: "FOR_RESALE", allocatedItemCost: 20 }];
  seed.sales = [{ id: "return-sale", inventoryItemId: "return-stock", quantitySold: 1, status: "Completed", grossSalePrice: 50, netProceeds: 50, realizedProfit: 40, allocatedCostOfGoodsSold: 10, saleDate: "2026-09-23", salesChannel: "Synthetic booth" }];
  const browser = await chromium.launch({ headless: true });
  let lastPage;
  try {
    for (const theme of ["light", "dark"]) for (const width of [360, 1440]) {
      const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: "reduce", timezoneId: "America/New_York", locale: "en-US" });
      const page = await context.newPage(); lastPage = page;
      page.setDefaultTimeout(20000);
      const errors = [];
      page.on("pageerror", (error) => errors.push(error.message));
      page.on("console", (message) => { if (message.type() === "error" && !/Failed to load resource|net::ERR_|favicon/i.test(message.text())) errors.push(message.text()); });
      page.on("dialog", (dialog) => dialog.accept());
      await context.route("**/*", (route) => {
        const url = new URL(route.request().url());
        if (url.origin !== base.origin || route.request().method() !== "GET") return route.abort();
        if (url.pathname.startsWith("/api/")) return route.fulfill({ contentType: "application/json", body: JSON.stringify({ configured: false, healthy: false }) });
        return route.continue();
      });
      await context.addInitScript(({ seed, theme }) => {
        if (sessionStorage.getItem("return-fixture")) return;
        localStorage.setItem("ember-and-tide.flip-scout.v1", JSON.stringify(seed));
        localStorage.setItem("et-tcg-app-theme", theme);
        sessionStorage.setItem("return-fixture", "1");
      }, { seed, theme });
      const go = async (route) => { await page.goto(new URL(`${route}?betaLocalMode=true`, base).href); await page.locator(".app[data-theme]").waitFor(); };
      const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem("ember-and-tide.flip-scout.v1")));
      const panel = () => page.getByRole("region", { name: "Fulfillment & returns", exact: true });
      const form = () => page.locator(".manual-lifecycle-form");
      const review = () => page.locator(".manual-lifecycle-review");
      const settlement = () => page.getByRole("region", { name: "Return settlement", exact: true });
      const save = async () => { await form().getByRole("button", { name: "Save record", exact: true }).click(); await review().waitFor(); };
      const openSale = async () => { await go("/business/sales"); await page.locator(".everyday-record-card").filter({ hasText: "$50.00" }).click(); await panel().getByRole("button", { name: "Inspected return", exact: true }).click(); };
      const capture = async (name) => {
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `${name}: no horizontal overflow`);
        assert.equal(await page.locator(".app").getAttribute("data-theme"), theme);
        assert.equal(await page.locator("vite-error-overlay").count(), 0);
        const undersized = await page.locator('.manual-lifecycles button:visible, .manual-lifecycle-form input:visible:not([type="checkbox"]), .manual-lifecycle-form select:visible, .manual-return-confirm:visible').evaluateAll((nodes) => nodes.filter((node) => node.getBoundingClientRect().height < 43.5).map((node) => node.outerHTML));
        assert.deepEqual(undersized, [], "44px touch targets");
        await page.screenshot({ path: path.join(output, `${name}-${theme}-${width}.png`), fullPage: true });
      };
      await openSale(); await panel().getByRole("button", { name: "Add Inspected return", exact: true }).click();
      await save();
      await expect(settlement()).toContainText("Receive and inspect");
      await review().getByRole("button", { name: "Edit record" }).click();
      await form().getByLabel("Status", { exact: true }).selectOption("Received"); await save();
      await review().getByRole("button", { name: "Edit record" }).click();
      await form().getByLabel("Status", { exact: true }).selectOption("Inspected");
      await form().getByLabel("Inspected disposition").selectOption("Restock review");
      await form().getByLabel("Inspection findings").fill("Synthetic inspection: same unit, resale condition verified.");
      await form().getByLabel("Additional refund amount").fill("40.00");
      await form().getByLabel("Manual refund reference").fill("SYN-REFUND-40");
      await save();
      const before = await saved(); assert.equal(before.sales[0].returnApplications?.length || 0, 0);
      await settlement().getByRole("button", { name: "Review stock & refund" }).click();
      await expect(settlement()).toContainText("Ready for your review");
      const apply = () => settlement().getByRole("button", { name: "Apply return & close record" });
      await expect(apply()).toBeDisabled();
      await capture("return-review");
      await settlement().getByRole("button", { name: "Cancel review" }).click();
      assert.deepEqual(await saved(), before, "Cancel review makes zero writes");
      await settlement().getByRole("button", { name: "Review stock & refund" }).click();
      const confirmation = settlement().getByRole("checkbox");
      await confirmation.focus();
      await page.keyboard.press("Shift+Tab");
      await page.keyboard.press("Tab");
      await expect(confirmation).toBeFocused();
      assert.ok(await confirmation.evaluate((node) => getComputedStyle(node).outlineStyle !== "none"), "Visible keyboard focus");
      await page.keyboard.press("Space"); await expect(confirmation).toBeChecked();
      await apply().click();
      await expect(page.getByText("Return applied on this device.", { exact: false })).toBeVisible();
      const after = await saved();
      await expect(page.locator(".ops-record-detail")).toContainText("9/23/2026");
      assert.deepEqual(after.inventory, seed.inventory, "Original acquisition unchanged");
      assert.equal(after.sales[0].returnApplications.length, 1);
      assert.equal(after.manualLifecycles[0].status, "Closed");
      await expect(review().getByRole("button", { name: "Edit record" })).toHaveCount(0);
      await expect(page.locator(".ops-detail-hero")).not.toContainText("400%");
      for (const key of Object.keys(seed.sales[0])) assert.deepEqual(after.sales[0][key], seed.sales[0][key], `Original sale ${key}`);
      await capture("return-applied");
      await openSale(); await panel().locator(".manual-lifecycle-card").first().click();
      await settlement().getByRole("button", { name: "Review stock & refund" }).click();
      await expect(settlement()).toContainText("Applied once");
      assert.equal(await apply().count(), 0);
      assert.deepEqual(await saved(), after, "Repeat review and reload make no duplicate application");
      const correction = () => page.getByRole("region", { name: "Return correction", exact: true });
      const reviewCorrection = async (reason, reference) => {
        await correction().getByLabel("Reason for correction").fill(reason);
        await correction().getByLabel("Manual refund reference").fill(reference);
        await correction().getByRole("button", { name: "Review correction", exact: true }).click();
      };
      const applyCorrection = async (name) => {
        const button = correction().getByRole("button", { name, exact: true });
        await expect(button).toBeDisabled();
        const confirm = correction().getByRole("checkbox");
        await confirm.focus(); await page.keyboard.press("Space");
        await button.click();
        await expect(correction()).toHaveCount(0);
        await expect(page.getByText("Return correction saved on this device.", { exact: false })).toBeVisible();
        await settlement().getByRole("button", { name: "Review stock & refund", exact: true }).click();
      };
      if (corrections) {
        await settlement().getByRole("button", { name: "Reverse applied return", exact: true }).click();
        await reviewCorrection("Synthetic mistaken return reversed", "SYN-REVERSAL-40");
        await expect(correction().getByRole("region", { name: "After", exact: true })).toContainText("$0.00");
        await capture("reversal-preview");
        await correction().getByRole("button", { name: "Cancel correction", exact: true }).click();
        assert.deepEqual(await saved(), after, "Reversal cancel makes zero writes");
        await settlement().getByRole("button", { name: "Reverse applied return", exact: true }).click();
        await reviewCorrection("Synthetic mistaken return reversed", "SYN-REVERSAL-40");
        await applyCorrection("Apply reversal");
        const reversed = await saved();
        assert.equal(reversed.sales[0].returnCorrections.length, 1);
        assert.equal(reversed.sales[0].returnCorrections[0].stockDelta, -1);
        assert.equal(reversed.sales[0].returnCorrections[0].refundDeltaMinor, -4000);
        assert.deepEqual(reversed.sales[0].returnApplications, after.sales[0].returnApplications);
        assert.deepEqual(reversed.manualLifecycles, after.manualLifecycles);
        assert.deepEqual(reversed.inventory, after.inventory);
        await page.reload(); await page.locator(".app[data-theme]").waitFor();
        await openSale(); await panel().locator(".manual-lifecycle-card").first().click();
        await settlement().getByRole("button", { name: "Review stock & refund", exact: true }).click();
        await expect(settlement()).toContainText("Correction history · 1");
        assert.deepEqual(await saved(), reversed, "Reload retains reversal without replaying mutation");
        await settlement().getByRole("button", { name: "Correct applied return", exact: true }).click();
        await correction().getByLabel(/^Corrected refund total/).fill("30.00");
        await correction().getByLabel("Corrected restocked quantity").fill("1");
        await correction().getByLabel("Corrected disposition").selectOption("Restock review");
        await correction().getByLabel("New inspection findings").fill("Synthetic fresh physical inspection of the same returned unit");
        await correction().getByRole("checkbox").check();
        await reviewCorrection("Synthetic revised refund and fresh restock", "SYN-CORRECTION-30");
        await capture("correction-preview");
        await applyCorrection("Apply correction");
        const corrected = await saved();
        assert.equal(corrected.sales[0].returnCorrections.length, 2);
        assert.equal(corrected.sales[0].returnCorrections[1].after.refundMinor, 3000);
        assert.equal(corrected.sales[0].returnCorrections[1].after.cogsReversalMinor, 1000);
        assert.deepEqual(corrected.sales[0].returnApplications, after.sales[0].returnApplications);
        assert.deepEqual(corrected.manualLifecycles, after.manualLifecycles);
        await settlement().locator("summary").click();
        await expect(settlement()).toContainText("Synthetic mistaken return reversed");
        await expect(settlement()).toContainText("Synthetic revised refund and fresh restock");
        await capture("correction-history");
      }
      await go("/business/money/reports");
      const report = page.locator(".manual-lifecycles").first();
      await report.getByLabel("Channel / booth").selectOption("Synthetic booth");
      const [download] = await Promise.all([page.waitForEvent("download"), report.getByRole("button", { name: "Download statement CSV" }).click()]);
      const csv = fs.readFileSync(await download.path(), "utf8");
      assert.match(csv, corrections ? /"50\.00","20\.00","30\.00","10\.00"/ : /"50\.00","10\.00","40\.00","10\.00"/);
      await capture("adjusted-report");
      await go("/business/inventory"); await page.getByRole("button", { name: "Open Synthetic Aurora pair", exact: true }).click();
      await expect(page.locator(".ops-record-detail")).toContainText("Quantity available");
      await go("/business/sales"); await page.getByRole("button", { name: "Record Sale", exact: true }).click();
      await page.getByLabel(/^Inventory item/).selectOption("return-stock");
      await page.getByLabel("Quantity sold", { exact: true }).fill("2");
      await page.getByLabel("Gross sale price", { exact: true }).fill("60");
      await page.getByLabel("Sales channel", { exact: true }).fill("Synthetic booth");
      await page.getByRole("button", { name: "Continue", exact: true }).click();
      await page.getByRole("button", { name: "Continue", exact: true }).click();
      await capture("resale-preview");
      await page.getByRole("button", { name: "Save Sale", exact: true }).click();
      await expect(page.getByRole("button", { name: "Record Sale", exact: true })).toBeVisible();
      const resold = await saved(); assert.equal(resold.sales.length, 2);
      const newSale = resold.sales.find((row) => row.id !== "return-sale");
      assert.equal(newSale.quantitySold, "2");
      assert.equal(Number(newSale.allocatedCostOfGoodsSold), 20);
      assert.equal(newSale.realizedProfit, 40);
      assert.equal(resold.sales.find((row) => row.id === "return-sale").returnApplications.length, 1);
      await go("/business/inventory"); await page.getByRole("button", { name: "Open Synthetic Aurora pair", exact: true }).click();
      await expect(page.locator(".ops-detail-hero")).toContainText("$0.00");
      if (corrections) {
        await openSale(); await panel().locator(".manual-lifecycle-card").first().click();
        await settlement().getByRole("button", { name: "Review stock & refund", exact: true }).click();
        const beforeBlocked = await saved();
        await settlement().getByRole("button", { name: "Reverse applied return", exact: true }).click();
        await reviewCorrection("Synthetic unsafe removal attempt", "SYN-BLOCKED");
        await expect(correction().getByRole("alert")).toBeVisible();
        assert.deepEqual(await saved(), beforeBlocked, "Resold returned unit reversal is blocked with zero writes");
        await expect(correction().getByRole("button", { name: "Apply reversal", exact: true })).toHaveCount(0);
        await capture("resold-reversal-blocked");
        await correction().getByRole("button", { name: "Cancel correction", exact: true }).click();
        await settlement().getByRole("button", { name: "Correct applied return", exact: true }).click();
        await correction().getByLabel(/^Corrected refund total/).fill("35.00");
        await reviewCorrection("Synthetic refund-only correction after resale", "SYN-CORRECTION-35");
        await applyCorrection("Apply correction");
        const final = await saved();
        const originalSale = final.sales.find(row => row.id === "return-sale");
        assert.equal(originalSale.returnCorrections.length, 3);
        assert.equal(originalSale.returnCorrections[2].stockDelta, 0);
        assert.equal(originalSale.returnCorrections[2].refundDeltaMinor, 500);
        assert.deepEqual(originalSale.returnApplications, after.sales[0].returnApplications);
        assert.deepEqual(final.manualLifecycles, after.manualLifecycles);
        await go("/business/money/reports");
        await report.getByLabel("Channel / booth").selectOption("Synthetic booth");
        const [finalDownload] = await Promise.all([page.waitForEvent("download"), report.getByRole("button", { name: "Download statement CSV" }).click()]);
        const finalCsv = fs.readFileSync(await finalDownload.path(), "utf8");
        assert.match(finalCsv, /"50\.00","15\.00","35\.00","10\.00"/);
        assert.match(finalCsv, /"60\.00","40\.00","0\.00","0\.00"/);
        await capture("corrected-report-after-resale");
      }
      assert.deepEqual(errors, [], "No page or application console errors");
      results.push({ theme, width, passed: true, checks: ["ordered receipt and inspection", "preview/cancel zero writes", "explicit keyboard confirmation", "atomic stock/refund application", "original acquisition and sale preserved", "reload idempotency", "CSV no double refund", "returned units resold with exact cost", "44px targets, focus, no overflow", ...(corrections ? ["reversal preview/cancel and reviewed apply", "immutable original histories", "reinspection before increased stock", "correction history on reload", "blocked reversal of resold units", "refund-only correction after resale", "corrected report exact costs and profit"] : [])] });
      await context.close();
    }
  } catch (error) {
    if (lastPage && !lastPage.isClosed()) { await lastPage.screenshot({ path: path.join(output, "failure.png"), fullPage: true }); fs.writeFileSync(path.join(output, "failure.txt"), await lastPage.locator("body").innerText()); }
    throw error;
  } finally { await browser.close(); }
  fs.writeFileSync(path.join(output, "results.json"), JSON.stringify({ passed: results.length, results }, null, 2));
  console.log(`Sale return workflow: ${results.length}/4 mobile/desktop light/dark contexts passed.`);
}
main().catch((error) => { fs.mkdirSync(output, { recursive: true }); fs.writeFileSync(path.join(output, "failure.json"), JSON.stringify({ completed: results, error: error.stack }, null, 2)); console.error(error); process.exitCode = 1; });
