export type MailboxPreview = Readonly<{
  format: typeof MAILBOX_IMPORT_FORMAT;
  candidates: readonly MailboxReceipt[];
  scannedMessages: number;
  skippedMessages: number;
  truncated: boolean;
  days: MailboxImportDays;
}>;

export type MailboxImportInput = {
  provider: MailboxProvider;
  mailboxAddress: string;
  appPassword: string;
  days: MailboxImportDays;
};

export class MailboxImportError extends Error {
  constructor(public readonly code: string, message: string, public readonly status = 400) {
    super(message);
    this.name = "MailboxImportError";
  }
}

export function validateMailboxImportInput(value: unknown): MailboxImportInput {
  if (!value || typeof value !== "object" || Array.isArray(value)
    || Object.keys(value).length !== 4
    || Object.keys(value).some((key) => !["provider", "mailboxAddress", "appPassword", "days"].includes(key))) {
    throw new MailboxImportError("mailbox_request_invalid", "Choose a mail provider, mailbox address, app password, and date range.");
  }
  const input = value as Record<string, unknown>;
  if (!MAILBOX_PROVIDERS.includes(input.provider as MailboxProvider)
    || !MAILBOX_IMPORT_DAYS.includes(input.days as MailboxImportDays)) {
    throw new MailboxImportError("mailbox_request_invalid", "Choose a supported mail provider and date range.");
  }
  if (typeof input.mailboxAddress !== "string" || input.mailboxAddress.length > 320
    || !/^[a-z0-9.!#$%&'*+/=?^_`{|}~-]+@[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?\.[a-z]{2,63}$/i.test(input.mailboxAddress.trim())) {
    throw new MailboxImportError("mailbox_request_invalid", "Enter a valid mailbox address.");
  }
  // App passwords are entered only here; they never become provider metadata,
  // order records, URL parameters, logs, or a stored connection.
  if (typeof input.appPassword !== "string" || input.appPassword.length > 256
    || /[\u0000-\u001f\u007f]/.test(input.appPassword) || input.appPassword.trim().replace(/ /g, "").length < 8) {
    throw new MailboxImportError("mailbox_request_invalid", "Enter the app password generated by your mail provider.");
  }
  return {
    provider: input.provider as MailboxProvider,
    mailboxAddress: input.mailboxAddress.trim().toLowerCase(),
    appPassword: input.appPassword.trim().replace(/ /g, ""),
    days: input.days as MailboxImportDays,
  };
}
